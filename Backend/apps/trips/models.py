import uuid
from django.db import models
from django.contrib.auth import get_user_model
from apps.catalog.models import FlightOffer, MasterHotel

User = get_user_model()

class Trip(models.Model):
    """The master trip plan created by user or AI."""
    STATUS_CHOICES = [
        ("PLANNING", "Planning"),
        ("ITINERARY_GENERATED", "Itinerary Generated"),
        ("BOOKING_IN_PROGRESS", "Booking In Progress"),
        ("CONFIRMED", "Confirmed"),
        ("ARCHIVED", "Archived"),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name="trips", null=True, blank=True)
    title = models.CharField(max_length=200)
    destination_city = models.CharField(max_length=100)
    origin_city = models.CharField(max_length=100)
    start_date = models.DateField()
    end_date = models.DateField()
    passenger_count = models.IntegerField(default=1)
    budget_ceiling = models.DecimalField(max_digits=10, decimal_places=2)
    currency = models.CharField(max_length=3, default="USD")
    status = models.CharField(max_length=30, choices=STATUS_CHOICES, default="PLANNING")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"{self.title} ({self.origin_city} -> {self.destination_city})"

    @property
    def total_estimated_cost(self):
        """Calculates total estimated cost across shortlisted items and itinerary days."""
        total = sum(day.day_cost_estimate for day in self.days.all())
        for item in self.shortlist_items.all():
            if item.item_type == "flight" and item.flight_offer:
                total += item.flight_offer.total_amount
            elif item.item_type == "hotel" and item.hotel:
                # Approximate hotel cost for the trip duration
                nights = max((self.end_date - self.start_date).days, 1)
                total += item.hotel.price_per_night * nights
        return total


class ItineraryDay(models.Model):
    """Daily itinerary block generated by Itinerary Agent."""
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    trip = models.ForeignKey(Trip, on_delete=models.CASCADE, related_name="days")
    day_number = models.IntegerField()
    date = models.DateField()
    theme = models.CharField(max_length=255)  # e.g. "Historic Temples & Traditional Markets"
    activities_json = models.JSONField(default=list)  # Morning, Afternoon, Evening blocks
    day_cost_estimate = models.DecimalField(max_digits=8, decimal_places=2, default=0.00)

    class Meta:
        ordering = ['day_number']
        unique_together = ('trip', 'day_number')

    def __str__(self):
        return f"{self.trip.title} - Day {self.day_number}: {self.theme}"


class TripShortlist(models.Model):
    """Saved flight or hotel recommendation attached to a trip."""
    ITEM_TYPES = [
        ("flight", "Flight"),
        ("hotel", "Hotel"),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    trip = models.ForeignKey(Trip, on_delete=models.CASCADE, related_name="shortlist_items")
    item_type = models.CharField(max_length=20, choices=ITEM_TYPES)
    flight_offer = models.ForeignKey(FlightOffer, on_delete=models.SET_NULL, null=True, blank=True, related_name="trip_shortlists")
    hotel = models.ForeignKey(MasterHotel, on_delete=models.SET_NULL, null=True, blank=True, related_name="trip_shortlists")
    is_selected_for_booking = models.BooleanField(default=False)
    notes = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"{self.trip.title} shortlist: {self.item_type}"

